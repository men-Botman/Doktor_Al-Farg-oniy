function resolvePath(object: Record<string, unknown>, key: string) {
  return key.split('.').reduce<unknown>((result, segment) => {
    if (typeof result === 'object' && result !== null && segment in result) {
      return (result as Record<string, unknown>)[segment]
    }

    return undefined
  }, object)
}

export function translate(locale: LanguageCode, key: string, variables: Record<string, string | number> = {}) {
  const selected = translations[locale] ?? translations.uz
  const value = resolvePath(selected as Record<string, unknown>, key)
  const finalText = typeof value === 'string' ? value : key

  return Object.entries(variables).reduce((result, [variable, replacement]) => {
    return result.replace(new RegExp(`\\{\\{${variable}\\}\\}`, 'g'), String(replacement))
  }, finalText)
}

